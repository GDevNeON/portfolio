import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import path from 'node:path'

const output = path.resolve('../.planning/spikes/001-a02-crystal-cave/evidence')
await fs.mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE } : {}) })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 })
page.setDefaultTimeout(30000)
const errors = [], checks = [], reports = {}, failedResponses = []
page.on('pageerror', e => errors.push(e.message))
page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()) })
page.on('response', r => { if (r.status() >= 400) failedResponses.push({ status: r.status(), url: r.url() }) })
const base = process.env.A02_URL || 'http://127.0.0.1:4173/a02.html'
const check = (name, condition) => { assert.ok(condition, name); checks.push(name); console.log('PASS', name) }
const nav = name => page.getByRole('navigation', { name: 'Các góc nhìn A02' }).getByRole('button', { name, exact: false })
const openTools = async () => { if (!(await page.getByRole('button', { name: 'Đóng tùy chỉnh' }).isVisible())) await page.getByRole('button', { name: 'Tùy chỉnh' }).click() }
const closeTools = async () => { if (await page.getByRole('button', { name: 'Đóng tùy chỉnh' }).isVisible()) await page.getByRole('button', { name: 'Đóng tùy chỉnh' }).click() }
async function report(name) {
  await openTools()
  const details = page.locator('.review-tools details')
  if (await details.getAttribute('open') === null) await details.locator('summary').click()
  const pending = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Tải báo cáo phiên xem' }).click()
  const file = path.join(output, name + '.json')
  await (await pending).saveAs(file)
  const data = JSON.parse(await fs.readFile(file, 'utf8'))
  reports[name] = data
  return data
}
const ready = () => page.getByRole('navigation', { name: 'Các góc nhìn A02' }).waitFor({ timeout: 120000 })
try {
  console.log('Opening', base)
  await page.goto(base, { waitUntil: 'domcontentloaded', timeout: 60000 })
  await ready()
  check('StrictMode leaves one canvas', await page.locator('canvas').count() === 1)
  await openTools()
  await page.getByRole('button', { name: 'Tạm dừng', exact: true }).click()
  await closeTools()
  for (const [name, file] of [['Bóng tối','01-entrance'],['Pha lê','02-crystal'],['Lữ hành','03-traveller'],['Ánh sáng','04-exit']]) {
    await nav(name).click()
    await page.waitForTimeout(700)
    await page.screenshot({ path: path.join(output, file + '.png') })
    check('Viewpoint ' + name, await nav(name).getAttribute('aria-current') === 'step')
  }
  await nav('Pha lê').click()
  const a = await report('physical-full')
  await page.waitForTimeout(700)
  const b = await report('paused')
  check('Pause freezes ambient clock and camera', a.ambientTime === b.ambientTime && a.state.progress === b.state.progress)
  await page.getByRole('button', { name: 'Đối chiếu art' }).click()
  check('Reference has both supplied images', await page.getByRole('dialog').locator('img').count() === 2)
  await page.getByRole('button', { name: 'Đóng ảnh tham chiếu' }).click()
  check('Reference preserves pause', await page.getByRole('button', { name: 'Tiếp tục', exact: true }).isVisible())
  await page.getByRole('button', { name: 'Tiếp tục', exact: true }).click()
  await page.waitForTimeout(1500)
  const alive = await report('idle-animation')
  check('Ambient runs with stationary camera', alive.ambientTime > b.ambientTime && alive.state.progress === b.state.progress)
  await closeTools()
  await page.mouse.move(720, 480)
  await page.mouse.wheel(0, 1200)
  await page.waitForTimeout(4000)
  const forward = await report('scroll-forward')
  check('Wheel advances bounded camera', forward.state.progress > 0.34 && forward.state.progress < 0.386)
  await closeTools()
  await page.mouse.move(720, 480)
  await page.mouse.wheel(0, -1200)
  await page.waitForTimeout(4000)
  const reverse = await report('scroll-reverse')
  check('Wheel reverses', reverse.state.progress < forward.state.progress)
  await page.getByLabel('Giảm chuyển động', { exact: true }).check()
  const reduced = await report('reduced-motion')
  await closeTools()
  await page.mouse.move(720, 480)
  await page.mouse.wheel(0, 5000)
  await page.waitForTimeout(600)
  const still = await report('reduced-still')
  check('Reduced motion stable, ignores wheel', reduced.state.progress === 0.34 && still.ambientTime === reduced.ambientTime && still.state.progress === reduced.state.progress)
  await closeTools()
  await page.locator('canvas').focus()
  await page.keyboard.press('ArrowDown')
  const keyboard = await report('keyboard')
  check('Reduced keyboard jumps next view', keyboard.state.progress === 0.68)
  await page.getByLabel('Chi tiết', { exact: false }).selectOption('low')
  const low = await report('low-detail')
  check('Low detail preserves position/motion', low.state.quality === 'low' && low.state.progress === 0.68 && low.state.reduced)
  check('Low detail reduces triangles', low.state.triangles < keyboard.state.triangles)
  await page.getByLabel('Chi tiết', { exact: false }).selectOption('full')
  await page.getByLabel('Pha lê — so sánh vật liệu').selectOption('mineral')
  await nav('Pha lê').click()
  const mineral = await report('mineral-full')
  check('Material switches at same viewpoint', mineral.state.material === 'mineral' && mineral.state.progress === 0.34)
  await closeTools()
  await page.screenshot({ path: path.join(output, '05-mineral-comparison.png') })
  await openTools()
  await page.getByLabel('Pha lê — so sánh vật liệu').selectOption('physical')
  await closeTools()
  await page.setViewportSize({ width: 600, height: 1200 })
  await page.waitForTimeout(600)
  await page.screenshot({ path: path.join(output, '06-portrait.png') })
  const portrait = await report('portrait')
  check('Resize preserves viewpoint', portrait.state.progress === 0.34 && portrait.viewport[0] === 600 && portrait.viewport[1] === 1200)
  await closeTools()
  await page.getByRole('button', { name: 'Ngắm cảnh', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  check('Phone can exit quiet mode', await page.getByRole('button', { name: 'Hiện chữ', exact: true }).isVisible())
  await page.getByRole('button', { name: 'Hiện chữ', exact: true }).click()
  await page.screenshot({ path: path.join(output, '07-phone.png') })
  check('Phone no horizontal overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await page.setViewportSize({ width: 844, height: 390 })
  await page.screenshot({ path: path.join(output, '08-phone-landscape.png') })
  check('Landscape fits height', await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.reload({ waitUntil: 'domcontentloaded' })
  await ready()
  const os = await report('os-reduced-start')
  check('OS reduced motion starts still', os.state.reduced && os.ambientTime === 0)
  const lost = await page.locator('canvas').evaluate(canvas => {
    const extension = canvas.getContext('webgl2')?.getExtension('WEBGL_lose_context')
    extension?.loseContext()
    return Boolean(extension)
  })
  check('Context loss extension available', lost)
  await page.getByRole('alert').waitFor()
  check('Context loss shows retry', await page.getByRole('button', { name: 'Thử lại', exact: true }).isVisible())
  await closeTools()
  await page.getByRole('button', { name: 'Thử lại', exact: true }).click()
  await ready()
  check('Retry restores single scene', await page.locator('canvas').count() === 1 && !(await page.getByRole('alert').isVisible()))
  check('Recovered scene ready', (await report('recovered')).state.ready)
  check('No JS or console errors', errors.length === 0)
  check('No failed HTTP responses', failedResponses.length === 0)
  console.log('COMPLETE', checks.length, 'checks')
} finally {
  await fs.writeFile(path.join(output, 'browser-checks.json'), JSON.stringify({ at: new Date().toISOString(), base, checks, errors, failedResponses, reports }, null, 2))
  await browser.close()
}
